#!/bin/sh
# Install / uninstall the PanVK Exynos 9611 ICD inside Termux.
#
# usage:
#   bash install-termux.sh                 # install from the directory containing this script
#   bash install-termux.sh --uninstall
#   ./scripts/install-termux.sh --from-zip dist/panvk-exynos9611-termux-v0.01.zip
#
# The installer never edits shell startup files. Use `panvk-run` or set VK_ICD_FILENAMES yourself.
set -eu

SELF_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PREFIX=${PREFIX:-/data/data/com.termux/files/usr}
LIBDIR="$PREFIX/lib/panvk-exynos9611"
ICDDIR="$PREFIX/etc/vulkan/icd.d"
ICD="$ICDDIR/panvk-exynos9611.json"
RUNNER="$PREFIX/bin/panvk-run"
MODE=install
ZIP=""

while [ $# -gt 0 ]; do
    case "$1" in
        --uninstall) MODE=uninstall ;;
        --from-zip)
            shift
            [ $# -gt 0 ] || { echo "error: --from-zip needs a path" >&2; exit 1; }
            ZIP=$1
            ;;
        --prefix)
            shift
            [ $# -gt 0 ] || { echo "error: --prefix needs a path" >&2; exit 1; }
            PREFIX=$1
            LIBDIR="$PREFIX/lib/panvk-exynos9611"
            ICDDIR="$PREFIX/etc/vulkan/icd.d"
            ICD="$ICDDIR/panvk-exynos9611.json"
            RUNNER="$PREFIX/bin/panvk-run"
            ;;
        -h|--help)
            sed -n '2,16p' "$0"
            exit 0
            ;;
        *) echo "error: unknown option: $1" >&2; exit 1 ;;
    esac
    shift
done

if [ "$MODE" = uninstall ]; then
    rm -f "$ICD" "$RUNNER"
    rm -rf "$LIBDIR"
    echo "removed PanVK Exynos 9611 from $PREFIX"
    exit 0
fi

if [ -n "$ZIP" ]; then
    command -v unzip >/dev/null 2>&1 || { echo "error: unzip is required" >&2; exit 1; }
    tmp=$(mktemp -d)
    trap 'rm -rf "$tmp"' EXIT INT TERM
    unzip -q "$ZIP" -d "$tmp"
    PREFIX="$PREFIX" sh "$tmp/install-termux.sh"
    exit $?
fi

[ -d "$PREFIX" ] || { echo "error: $PREFIX does not exist; run this inside Termux" >&2; exit 1; }
[ -f "$SELF_DIR/libvulkan_panfrost.so" ] || {
    echo "error: libvulkan_panfrost.so is missing next to this script" >&2; exit 1
}
[ -f "$SELF_DIR/panvk-exynos9611.json" ] || {
    echo "error: panvk-exynos9611.json is missing next to this script" >&2; exit 1
}

mkdir -p "$LIBDIR" "$ICDDIR" "$PREFIX/bin"
cp "$SELF_DIR/libvulkan_panfrost.so" "$LIBDIR/libvulkan_panfrost.so"
sed "s|@LIBDIR@|$LIBDIR|g" "$SELF_DIR/panvk-exynos9611.json" > "$ICD"

cat > "$RUNNER" <<EOF
#!$PREFIX/bin/sh
# Generated by panvk-exynos9611-kbase-termux. Runs a command with only the PanVK ICD visible.
export VK_ICD_FILENAMES="$ICD"
exec "\$@"
EOF
chmod 755 "$RUNNER" "$LIBDIR/libvulkan_panfrost.so"

echo "installed:"
echo "  $LIBDIR/libvulkan_panfrost.so"
echo "  $ICD"
echo "  $RUNNER"
echo
echo "test with:"
echo "  panvk-run vulkaninfo --summary"
